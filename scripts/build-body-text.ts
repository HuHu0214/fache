import {
  mkdirSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { extractMdxText } from '../src/content/mdx-text';
import { scanMdx } from './lib/parse-mdx';

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const scenarioBodies: Record<string, string> = {};
const conceptBodies: Record<string, string> = {};

for (const file of walk(path.resolve('content/themes'))) {
  if (!file.endsWith('.mdx')) {
    continue;
  }
  const kind = path.basename(path.dirname(file));
  const source = readFileSync(file, 'utf8');
  const frontmatter = scanMdx(source).frontmatter as { id?: string };
  if (!frontmatter.id) {
    throw new Error(`缺少 id：${file}`);
  }
  const text = extractMdxText(source);
  if (kind === 'scenarios') {
    scenarioBodies[frontmatter.id] = text;
  } else if (kind === 'concepts') {
    conceptBodies[frontmatter.id] = text;
  }
}

const output = `// Generated by scripts/build-body-text.ts. Do not edit.
export const scenarioBodies: Record<string, string> = ${JSON.stringify(
  scenarioBodies,
  null,
  2,
)};

export const conceptBodies: Record<string, string> = ${JSON.stringify(
  conceptBodies,
  null,
  2,
)};
`;

mkdirSync('src/generated', { recursive: true });
writeFileSync('src/generated/body-text.ts', output);
console.log(
  `body text: ${Object.keys(scenarioBodies).length} scenarios, ${Object.keys(conceptBodies).length} concepts`,
);
