import {
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import type { LawFile } from '../src/content/schema';

const lawsDir = path.resolve('content/laws');
const laws = readdirSync(lawsDir)
  .filter((file) => file.endsWith('.json'))
  .map((file) => {
    const data = JSON.parse(
      readFileSync(path.join(lawsDir, file), 'utf8'),
    ) as LawFile;
    return data.law;
  })
  .sort(
    (a, b) =>
      (a.categoryOrder ?? 99) - (b.categoryOrder ?? 99) ||
      a.title.localeCompare(b.title, 'zh-CN'),
  );

const output = `// Generated by scripts/build-law-index.ts. Do not edit.
import type { Law } from '../content/schema';

export const lawIndex: Law[] = ${JSON.stringify(laws, null, 2)};
`;

mkdirSync('src/generated', { recursive: true });
writeFileSync('src/generated/law-index.ts', output);
console.log(
  `law index: ${laws.length} laws, ${laws.reduce(
    (sum, law) => sum + law.articleCount,
    0,
  )} articles`,
);
